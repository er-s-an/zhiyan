export function pickLang(lang: Lang, zh: string, en: string, fr: string, ja: string): string {
  if (lang === "zh") return zh;
  if (lang === "fr") return fr;
  if (lang === "ja") return ja;
  if (lang === "ru") return RU[en] ?? en;
  if (lang === "ko") return KO[en] ?? en;
  return en;
}

export function overlay(lang: "ru" | "ko", en: string): string | undefined {
  return lang === "ru" ? RU[en] : KO[en];
}
